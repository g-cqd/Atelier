    @Test
    func `serialized indentation state round trips and empty state resets it`() {
        var scanner = YAMLExternalScanner()
        var lexer = StringScannerLexer("- one")
        let valid = YAMLExternalScanner.externalNames.map { $0 == "_r_blk_seq_bgn" }
        #expect(scanner.scan(&lexer, validSymbols: valid))
        var state: [UInt8] = []
        scanner.serialize(into: &state)
        var restored = YAMLExternalScanner()
        restored.deserialize(state[...])
        var roundTrip: [UInt8] = []
        restored.serialize(into: &roundTrip)
        #expect(roundTrip == state)
        restored.deserialize([])
        var reset: [UInt8] = []
        restored.serialize(into: &reset)
        var initial: [UInt8] = []
        YAMLExternalScanner().serialize(into: &initial)
        #expect(reset == initial)
    }

    @Test
    func `maximum indentation state stays within the parser buffer`() {
        var state: [UInt8] = [0, 0, 0, 0, 255, 255, 255, 255, 0, 0]
        for _ in 0 ..< 253 { state.append(contentsOf: [109, 0, 0, 0]) }
        var scanner = YAMLExternalScanner()
        scanner.deserialize(state[...])
        var serialized: [UInt8] = []
        scanner.serialize(into: &serialized)
